@dataclass(frozen=True, slots=True)
class GreetingReply:
    kind: GreetingKind
    style: str
    text: str


def _normalized(text: str) -> str:
    cleaned = _NORMALIZE_RE.sub(" ", str(text).casefold().replace("ё", "е"))
    return " ".join(cleaned.split())


def detect_greeting(text: str | None) -> GreetingKind | None:
    """Recognize short explicit greetings, not incidental morning/night words."""
    if not isinstance(text, str):
        return None
    value = _normalized(text)
    if not value or len(value.split()) > 5:
        return None
    if value in _MORNING_FORMS:
        return "morning"
    if value in _NIGHT_FORMS:
        return "night"
    return None


def _tokens(messages: Iterable[str]) -> list[str]:
    value = " ".join(str(item) for item in messages if item)
    return _normalized(value).split()


def _context_style(context_messages: Iterable[str], rng: random.Random) -> str:
    counts: dict[str, int] = {}
    context = _tokens(tuple(context_messages)[-8:])
    for style, keywords in _STYLE_KEYWORDS.items():
        counts[style] = sum(1 for token in context if token in keywords)
    best = max(counts.values(), default=0)
    if best > 0:
        candidates = sorted(style for style, score in counts.items() if score == best)
        return rng.choice(candidates)
    return rng.choice(tuple(_REPLIES))


def choose_greeting_reply(
    kind: GreetingKind,
    *,
    context_messages: Iterable[str],
    recent_replies: Iterable[str],
    rng: random.Random,
) -> GreetingReply:
    """Choose one curated meme response from context, never from user identity."""
    if kind not in {"morning", "night"}:
        raise ValueError(f"Unsupported greeting kind: {kind}")
    style = _context_style(context_messages, rng)
    options = list(_REPLIES[style][kind])
    recent = {_normalized(item) for item in recent_replies if item}
    fresh = [item for item in options if _normalized(item) not in recent]
    if fresh:
        options = fresh
    return GreetingReply(kind=kind, style=style, text=rng.choice(options))


def iter_greeting_texts() -> Iterable[str]:
    for variants in _REPLIES.values():
        for kind in ("morning", "night"):
            yield from variants[kind]


