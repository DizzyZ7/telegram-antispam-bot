def _surreal_greeting(kind: GreetingKind, recent: set[str], rng: random.Random) -> str | None:
    """Bounded sampling from 2,304 combinations; no unbounded retry loops."""
    for _ in range(24):
        text = (
            f"{rng.choice(_SURREAL_OPENERS[kind])} "
            f"{rng.choice(_SURREAL_ACTORS).capitalize()} "
            f"{rng.choice(_SURREAL_EVENTS)}. "
            f"{rng.choice(_SURREAL_ENDINGS)}"
        )
        if _normalized(text) not in recent:
            return text
    return None


@dataclass(frozen=True, slots=True)
class GreetingReply:
    kind: GreetingKind
    style: str
    text: str


def _normalized(text: str) -> str:
    cleaned = _NORMALIZE_RE.sub(" ", str(text).casefold().replace("ё", "е"))
    return " ".join(cleaned.split())


def detect_greeting(text: str | None) -> GreetingKind | None:
    """Recognize short explicit greetings, not incidental morning/night words."""
    if not isinstance(text, str):
        return None
    value = _normalized(text)
    if not value or len(value.split()) > 6:
        return None
    # "Фосген, спокойной ночи!" is just as intentional as the unaddressed
    # greeting. Never match a longer sentence merely containing these words.
    parts = value.split()
    if parts and parts[0] in {"фосген", "fosgen"}:
        parts = parts[1:]
    if parts and parts[-1] in {"фосген", "fosgen"}:
        parts = parts[:-1]
    value = " ".join(parts)
    if value in _MORNING_FORMS:
        return "morning"
    if value in _NIGHT_FORMS:
        return "night"
    return None


def _tokens(messages: Iterable[str]) -> list[str]:
    value = " ".join(str(item) for item in messages if item)
    result: list[str] = []
    for raw in _normalized(value).split():
        result.append(raw)
        analysed = analyze_token(raw)
        lemma = (analysed.lemma or analysed.normalized).casefold()
        if lemma and lemma != raw:
            result.append(lemma)
    return result


def _context_style(context_messages: Iterable[str], rng: random.Random) -> str:
    counts: dict[str, int] = {}
    context = _tokens(tuple(context_messages)[-8:])
    for style, keywords in _STYLE_KEYWORDS.items():
        counts[style] = sum(1 for token in context if token in keywords)
    best = max(counts.values(), default=0)
    if best > 0:
        candidates = sorted(style for style, score in counts.items() if score == best)
        return rng.choice(candidates)
    # When context lacks a clear theme, use Fosgen's familiar witty voice
    # instead of a randomly selected specialized science/engineering persona.
    return rng.choice(("neutral", "absurd", "gaming", "animals", "cosmos", "food", "office", "technical", "science", "literary", "reader", "art", "engineering"))


