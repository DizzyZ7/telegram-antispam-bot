def _key(value: str) -> str:
    return " ".join(_NORMALIZE.sub(" ", value.casefold().replace("ё", "е")).split())


def choose_autonomous_joke(recent_outputs: list[str], rng: random.Random) -> str | None:
    """Avoid repeats, including repeated jokes with changed punctuation."""
    seen = {_key(item) for item in recent_outputs}
    candidates = [joke for joke in JOKES if _key(joke) not in seen and is_safe_entertainment_reply(joke)]
    return rng.choice(candidates) if candidates else None
