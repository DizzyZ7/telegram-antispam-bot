def birthday_greeting(chat_id: int, local_date: date) -> str:
    digest = hashlib.sha256(f"birthday-v1:{chat_id}:{local_date.isoformat()}".encode()).digest()
    # Rotate the introduction so adjacent celebration days differ, with
    # independently selected complete wish/closing paragraphs (2304 variants).
    opening = _OPENINGS[(local_date.toordinal() + abs(int(chat_id))) % len(_OPENINGS)]
    wish = _WISHES[digest[0] % len(_WISHES)]
    closing = _CLOSINGS[digest[1] % len(_CLOSINGS)]
    return f"С днем рождения! 🎂💛\n\n{opening}\n\n{wish}\n\n{closing}"
